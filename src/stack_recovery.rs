    struct FakeRecoveryProvider {
        pulls: BTreeMap<PrNumber, PullRequestSnapshot>,
        disposition: GitHubStackMutationDisposition,
        creates: std::cell::Cell<u32>,
    }

    impl NativeStackRecoveryProvider for FakeRecoveryProvider {
        fn verify_precondition_with_checks(
            &self,
            _repository: &RepositoryId,
            expected: &PullRequestPrecondition,
        ) -> Result<PullRequestSnapshot, MutationError> {
            self.verify(expected, true)
        }

        fn verify_precondition(
            &self,
            _repository: &RepositoryId,
            expected: &PullRequestPrecondition,
        ) -> Result<PullRequestSnapshot, MutationError> {
            self.verify(expected, false)
        }

        fn converge_membership(
            &self,
            plan: &NativeMembershipPlan,
        ) -> Result<NativeMembershipReceipt, NativeMembershipError> {
            self.creates.set(self.creates.get() + 1);
            let (repository, operation_id, actor, operation, desired) = match plan {
                NativeMembershipPlan::Create { plan } => (
                    plan.desired.base.repository.clone(),
                    plan.operation_id.clone(),
                    plan.actor.clone(),
                    crate::github::GitHubStackMutationOperation::Create,
                    plan.desired.clone(),
                ),
                NativeMembershipPlan::Add {
                    repository,
                    operation_id,
                    actor,
                    expected_members,
                    candidate,
                    ..
                } => {
                    let pulls = expected_members
                        .iter()
                        .map(|number| &self.pulls[number])
                        .chain(std::iter::once(candidate.as_ref()))
                        .collect::<Vec<_>>();
                    let desired = crate::stack_membership::topology_from_members(
                        &pulls[0].base,
                        pulls.iter().copied(),
                    )?;
                    (
                        repository.clone(),
                        operation_id.clone(),
                        actor.clone(),
                        crate::github::GitHubStackMutationOperation::Add,
                        desired,
                    )
                }
                NativeMembershipPlan::AbsentSingleton { .. } => {
                    return Err(NativeMembershipError::InvalidPlan {
                        code: "fixture_singleton".to_owned(),
                        message: "unexpected singleton".to_owned(),
                    });
                }
            };
            let receipt = GitHubStackMutationReceipt {
                schema_version: 1,
                operation_id,
                operation,
                repository: repository.clone(),
                actor,
                disposition: self.disposition,
                request: crate::github::GitHubStackRequestIdentity {
                    method: "POST".to_owned(),
                    path: format!("repos/{}/stacks", repository.slug()),
                    ordered_pull_requests: desired.entries.iter().map(|entry| entry.pr).collect(),
                    github_request_id: Some("request-1".to_owned()),
                },
                before: None,
                after: Some(crate::github::GitHubStackGeneration {
                    id: 1,
                    number: 7,
                    node_id: "S_recovered".to_owned(),
                    open: true,
                    created_at: "2026-08-08T00:00:00Z".to_owned(),
                    topology: desired,
                }),
                provider_output: None,
                evidence_hash: String::new(),
            }
            .seal();
            Ok(NativeMembershipReceipt::StackMutation {
                receipt: Box::new(receipt),
            })
        }
    }

    impl FakeRecoveryProvider {
        fn verify(
            &self,
            expected: &PullRequestPrecondition,
            include_checks: bool,
        ) -> Result<PullRequestSnapshot, MutationError> {
            let actual = self.pulls[&expected.number].clone();
            let actual_precondition = PullRequestPrecondition::from(&actual);
            let identity_matches = expected.mutation_identity_eq(&actual_precondition);
            let checks_match = !include_checks || expected.checks == actual_precondition.checks;
            if identity_matches && checks_match {
                Ok(actual)
            } else {
                Err(MutationError::StalePrecondition {
                    expected: Box::new(expected.clone()),
                    actual: Box::new(actual_precondition),
                    changed_fields: vec!["fixture_generation".to_owned()],
                })
            }
        }
    }

