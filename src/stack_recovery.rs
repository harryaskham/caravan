//! Receipt-gated recovery for a multi-member caravan missing its native Stack.
//!
//! Ordinary membership remains the only authority that labels and retargets
//! pull requests. This command repairs only the provider representation after
//! those mutations are already exact. Preview seals current repository,
//! membership, head/base, check, rollout and mapping evidence into a plan hash;
//! apply independently rediscovers the same evidence before issuing at most one
//! idempotent Stack create/add request. It never rewrites a source head or changes a
//! PR base, label, comment, or merge state.

